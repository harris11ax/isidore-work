// content.db -> the site's committed data.
//
// Writes src/data/{projects.json,domains.ts,roles.ts,project-roles.ts,site.ts} and
// copies every referenced media file into public/. Files are only rewritten when
// their contents actually change, so an unchanged publish produces no git noise.
//
// Nothing this module writes may carry a local filesystem path — the check at the
// bottom refuses to publish if one appears (see AGENTS.md).
import fs from 'node:fs';
import path from 'node:path';
import { REPO, MEDIA_DIR, db, listDomains, listProjects, listRoles, listEducation, allSettings, roleIdForProject, assetsFor } from './db.mjs';

const DATA = path.join(REPO, 'src', 'data');
const PUBLIC = path.join(REPO, 'public');
const PROJECTS_PUBLIC = path.join(PUBLIC, 'projects');
const MANIFEST = path.join(PROJECTS_PUBLIC, '.generated-media.json');

const pj = (v, fallback = []) => {
	try {
		return JSON.parse(v);
	} catch {
		return fallback;
	}
};

const written = new Map(); // path -> true (files this run wrote)
const stats = { files: 0, unchanged: 0, media: 0, projects: 0, skippedHidden: 0 };

function writeIfChanged(file, contents) {
	written.set(file, true);
	let current = null;
	try {
		current = fs.readFileSync(file, 'utf8');
	} catch {
		/* new file */
	}
	if (current === contents) {
		stats.unchanged++;
		return false;
	}
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, contents);
	stats.files++;
	return true;
}

/**
 * Resolve a stored media reference to a published URL, copying the file into
 * place. Accepts `media:<id>`, an absolute site path, or an external URL.
 */
function publishMedia(value, { slug = null, name = null } = {}) {
	if (!value) return '';
	if (typeof value !== 'string') return '';
	if (/^https?:/i.test(value)) return value;

	if (value.startsWith('media:')) {
		const id = Number(value.slice(6));
		const row = db.prepare('SELECT * FROM media WHERE id = ?').get(id);
		if (!row) return '';
		const dir = slug ? path.join(PROJECTS_PUBLIC, slug) : path.join(PUBLIC, 'media');
		const dest = path.join(dir, row.file);
		fs.mkdirSync(dir, { recursive: true });
		const source = path.join(MEDIA_DIR, row.file);
		if (!fs.existsSync(source)) return '';
		let same = false;
		try {
			same = fs.statSync(source).size === fs.statSync(dest).size;
		} catch {
			same = false;
		}
		if (!same) fs.copyFileSync(source, dest);
		stats.media++;
		const url = slug ? `/projects/${slug}/${row.file}` : `/media/${row.file}`;
		track(url);
		return url;
	}

	// already a site path — leave it alone
	return value;
}

// Track generated public files so a removed asset does not leave its file behind.
const generatedFiles = new Set();

function track(url) {
	if (url.startsWith('/projects/')) generatedFiles.add(url.replace(/^\//, ''));
	else if (url.startsWith('/media/')) generatedFiles.add(url.replace(/^\//, ''));
}

