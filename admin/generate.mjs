// ------------------------------------------------------------- projects -----
const projects = listProjects();
const records = [];
for (const p of projects) {
	if (!p.visible) {
		stats.skippedHidden++;
		continue;
	}
	const assets = [];
	for (const a of assetsFor(p.id)) {
		const src = publishMedia(a.src, { slug: p.slug });
		if (!src) continue;
		const entry = { type: a.type || 'image', src };
		if (a.caption) entry.caption = a.caption;
		if (a.thumb) entry.thumb = publishMedia(a.thumb, { slug: p.slug });
		assets.push(entry);
	}
	const cover = p.cover ? publishMedia(p.cover, { slug: p.slug }) : '';

	const rec = {
		slug: p.slug,
		name: p.name,
		date: p.date,
		domain: p.domain_slug,
		category: p.category,
		audience: p.audience,
		effort: p.effort,
		timeHours: p.time_hours,
		summary: p.summary,
		hasVisuals: assets.length > 0 || Boolean(cover),
		tags: pj(p.tags),
		assets,
	};
	if (cover) rec.cover = cover;
	if (p.accent_color) rec.accentColor = p.accent_color;
	if (p.body) rec.body = p.body;
	if (p.course) rec.course = p.course;
	if (p.term) rec.term = p.term;
	if (p.org) rec.org = p.org;
	if (p.kind) rec.kind = p.kind;
	if (p.status) rec.status = p.status;
	const deliverables = pj(p.deliverables);
	const tools = pj(p.tools);
	if (deliverables.length) rec.deliverables = deliverables;
	if (tools.length) rec.tools = tools;
	if (p.redirect_from) rec.redirectFrom = p.redirect_from;
	records.push(rec);
}
// Newest first. Equal dates keep the database order (sort_order, preserved from the
// original file), and Array.prototype.sort is stable — so this is deterministic and
// re-running generate never reorders the file.
records.sort((a, b) => (a.date === b.date ? 0 : a.date < b.date ? 1 : -1));

writeIfChanged(path.join(DATA, 'projects.json'), `${JSON.stringify(records, null, '\t')}\n`);
stats.projects = records.length;

// ------------------------------------------------------- project -> role ----
const roleMap = {};
for (const p of projects) {
	const roleId = roleIdForProject(p.slug);
	if (roleId) roleMap[p.slug] = roleId;
}
// Sorted so the file does not depend on database row order — a re-import must
// produce byte-identical output.
const anchors = {};
for (const slug of Object.keys(roleMap).sort()) anchors[slug] = roleMap[slug];
writeIfChanged(
	path.join(DATA, 'project-roles.ts'),
	`// GENERATED by admin/generate.mjs — the CV role each Work-category project came
// out of. Edit through /admin (the project form's "CV role" field).

export const ROLE_BY_SLUG: Record<string, string> = ${JSON.stringify(anchors, null, '\t')};
`,
);

// --------------------------------------------------- stale media cleanup ----
// Only safe because the manifest lists exactly what a previous run produced. The
// guard below matters: a run against an empty or broken database would otherwise
// delete every published asset (including files tracked in git).
let previous = [];
try {
	previous = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
} catch {
	previous = [];
}
let removed = 0;
if (generatedFiles.size === 0 && previous.length > 0) {
	console.warn(
		`generate: REFUSING stale-media cleanup — this run produced 0 published files but the ` +
			`manifest lists ${previous.length}. That means the content database is empty or the ` +
			`build is broken. Is the publish pipeline failing upstream?`,
	);
} else {
	for (const rel of previous) {
		if (generatedFiles.has(rel)) continue;
		const file = path.join(PUBLIC, rel);
		if (fs.existsSync(file)) {
			fs.unlinkSync(file);
			removed++;
		}
	}
	for (const rel of generatedFiles) {
		const dir = path.dirname(path.join(PUBLIC, rel));
		try {
			if (fs.existsSync(dir) && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
		} catch {
			/* not empty / not ours */
		}
	}
	fs.mkdirSync(PROJECTS_PUBLIC, { recursive: true });
	fs.writeFileSync(MANIFEST, JSON.stringify([...generatedFiles].sort(), null, '	'));
}

// ------------------------------------------------------------ safety net ----
const suspects = [path.join(DATA, 'site.ts'), path.join(DATA, 'projects.json'), path.join(DATA, 'roles.ts')];
const LEAK = /(?:[A-Za-z]:\\\\|\/home\/izzy\/|\/Users\/|Google Drive|OneDrive)/;
for (const file of suspects) {
	const text = fs.readFileSync(file, 'utf8');
	if (LEAK.test(text)) {
		throw new Error(`refusing to publish: ${file} contains a local filesystem path`);
	}
}

console.log(
	`generate: ${stats.projects} projects (${stats.skippedHidden} hidden), ${stats.media} media files, ` +
		`${stats.files} written, ${stats.unchanged} unchanged, ${removed} stale removed`,
);
